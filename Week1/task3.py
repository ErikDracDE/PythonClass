zahl = 10;
print('Int variable of value ' + zahl + " converted to floating-point is: " + float(zahl));

kommazahl = 10.2;
print('Floating point variable of value ' + kommazahl + " converted to integer is: " + int(kommazahl));

neuZahl = 7;
print('Int variable of value ' + neuZahl + " converted to string is: " + str(neuZahl));

textNo = '32';
print('String variable of value ' + textNo + " converted to int is: " + int(textNo));

boolZahl = 39;
print('Int variable of value ' + boolZahl + " converted to boolean is: " + bool(boolZahl));